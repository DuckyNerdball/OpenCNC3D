#!/usr/bin/env python3
"""Writes RALLYT01.INI and RALLYT01.BIN, a small Rally test course for rally_probe.

A 64x64 classic-format multiplayer map (cell = y*64 + x in the INI; the engine moves
it into its 128x128 layout keeping x and y), clear temperate terrain, a serpentine
point-to-point track five cells wide whose edges are sandbag walls, a start grid of
eight slots, twelve crate spots, two Nod guard towers and an advanced guard tower
beside the track with no power plant (Rally treats the hostile house as powered),
and two Nod riflemen standing on the track to be run over.

    python3 brain/host/rally_test/make_test_course.py [output_dir]
"""
import os
import sys

W = H = 64
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
NAME = "RALLYT01"
HALF = 2  # corridor cells either side of the centre cell

# Centre line corners in cells (the cell's centre is +0.5).
CORNERS = [(8, 50), (8, 10), (20, 10), (20, 50), (32, 50), (32, 10), (44, 10), (44, 54)]


def lep(c):
    """cell index -> lepton coordinate of the cell centre"""
    return c * 256 + 128


# Driveable cells: each straight expanded by HALF cells, plus the start box behind P0
# and the run-off past the finish.
drive = set()


def box(x0, y0, x1, y1):
    for y in range(min(y0, y1), max(y0, y1) + 1):
        for x in range(min(x0, x1), max(x0, x1) + 1):
            drive.add((x, y))


for (ax, ay), (bx, by) in zip(CORNERS, CORNERS[1:]):
    box(min(ax, bx) - HALF, min(ay, by) - HALF, max(ax, bx) + HALF, max(ay, by) + HALF)
box(8 - HALF, 50, 8 + HALF, 58)    # start grid
box(44 - HALF, 54, 44 + HALF, 58)  # run-off after the finish line

walls = set()
for (x, y) in drive:
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1):
            n = (x + dx, y + dy)
            if n not in drive:
                walls.add(n)
assert all(1 <= x < W - 1 and 1 <= y < H - 1 for x, y in walls)

# Course points every two cells along the centre line, in leptons.
points = []
for (ax, ay), (bx, by) in zip(CORNERS, CORNERS[1:]):
    steps = max(abs(bx - ax), abs(by - ay)) // 2
    for i in range(steps):
        points.append((lep(ax + (bx - ax) * i // steps), lep(ay + (by - ay) * i // steps)))
points.append((lep(CORNERS[-1][0]), lep(CORNERS[-1][1])))
HW = (HALF * 2 + 1) * 128  # half width in leptons: two and a half cells

grid = []
for i in range(8):
    col = i % 2
    row = i // 2
    x = 7.25 if col == 0 else 9.75
    y = 51.2 + row * 1.4 + (0.7 if col else 0.0)
    grid.append((int(x * 256), int(y * 256)))

crates = []
for cx, cy in ((8, 32), (20, 30), (32, 30), (44, 30)):  # a row across each long leg
    for off in (-2, 0, 2):
        crates.append((lep(cx + off), lep(cy)))

finish = (42 * 256, 52 * 256, 47 * 256, 52 * 256)


def cell(x, y):
    return y * 64 + x


lines = []
add = lines.append
add("; Rally test course for brain/host/rally_probe.cpp, generated by make_test_course.py")
add("[Basic]")
add("Name=Rally Test Course")
add("Player=Multi1")
add("BuildLevel=99")
add("Intro=x")
add("Brief=x")
add("Win=x")
add("Lose=x")
add("Action=x")
add("Theme=No theme")
add("")
add("[MAP]")
add("Theater=TEMPERATE")
add("X=1")
add("Y=1")
add("Width=62")
add("Height=62")
add("")
for i in range(1, 9):
    add("[Multi%d]" % i)
    add("Allies=Multi%d" % i)
    add("MaxBuilding=150")
    add("MaxUnit=150")
    add("Edge=North")
    add("Credits=0")
    add("")
for house in ("GoodGuy", "BadGuy", "Neutral", "Special"):
    add("[%s]" % house)
    add("Allies=%s" % house)
    add("MaxBuilding=150")
    add("MaxUnit=150")
    add("Edge=North")
    add("Credits=0")
    add("")
add("[Waypoints]")
for i, (gx, gy) in enumerate(grid):
    add("%d=%d" % (i, cell(gx // 256, gy // 256)))
add("")
add("[STRUCTURES]")
add("000=BadGuy,GTWR,256,%d,0,None" % cell(12, 20))
add("001=BadGuy,GTWR,256,%d,0,None" % cell(28, 36))
add("002=BadGuy,ATWR,256,%d,0,None" % cell(24, 30))
add("")
add("[INFANTRY]")
add("000=BadGuy,E1,256,%d,0,Guard,0,None" % cell(32, 40))
add("001=BadGuy,E1,256,%d,0,Guard,0,None" % cell(31, 22))
add("")
add("[UNITS]")
add("")
add("[OVERLAY]")
for (x, y) in sorted(walls, key=lambda c: (c[1], c[0])):
    add("%d=SBAG" % cell(x, y))
add("")
add("[Rally]")
add("Name=Rally Test Course")
add("Hostile=BadGuy")
add("Points=%d" % len(points))
for i, (x, y) in enumerate(points):
    add("P%03d=%d,%d,%d" % (i, x, y, HW))
add("GridFacing=0")
for i, (x, y) in enumerate(grid):
    add("Grid%d=%d,%d" % (i, x, y))
add("Finish=%d,%d,%d,%d" % finish)
add("Crates=%d" % len(crates))
for i, (x, y) in enumerate(crates):
    add("C%02d=%d,%d" % (i, x, y))
add("")

with open(os.path.join(OUT, NAME + ".INI"), "w", newline="\r\n") as f:
    f.write("\n".join(lines))
with open(os.path.join(OUT, NAME + ".BIN"), "wb") as f:
    f.write(bytes([0xFF, 0x00]) * (W * H))
print("wrote %s: %d points, %d wall cells, %d crates" % (os.path.join(OUT, NAME), len(points), len(walls), len(crates)))
