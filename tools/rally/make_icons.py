def cloud(c, parts, mat="smoke", base=0.55):
    """A cloud from overlapping puffs, each puff a lit sphere."""
    m_all = np.zeros((c.h, c.w), bool)
    for cx, cy, rx, ry in parts:
        m = ellipse(c, cx, cy, rx, ry)
        sh = sphere_shade(c, cx, cy, rx, ry, amb=base, kd=0.45, ks=0.0)
        c.paint(m, mat, sh, dither=0.8)
        m_all |= m
    return m_all


