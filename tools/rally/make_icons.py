def load_palette():
    """TEMPERAT.PAL from the disc, widened like the engine: 256 (r, g, b) tuples."""
    sys.path.insert(0, os.path.join(ROOT, "menu", "tools"))
    import mixshp  # noqa: E402  (the repo's port of the engine's MIX reader)
    mixes = mixshp.MixSet(DOSDATA, ["TEMPERAT.MIX"])
    if not mixes.mixes:
        raise SystemExit("no TEMPERAT.MIX under %s: the palette comes from the disc data"
                         % DOSDATA)
    raw = mixes.read("TEMPERAT.PAL")
    if len(raw) != 768:
        raise SystemExit("TEMPERAT.PAL is %d bytes, expected 768" % len(raw))
    return [tuple(min(252, (raw[i * 3 + k] & 0x3F) << 2) for k in range(3))
            for i in range(256)]


