def icon_none():
    """The empty item slot: a dark recess inside the cameo frame. The recess is lit
    from the upper left like everything else, so its top and left walls are in
    shadow and its bottom and right walls catch the light."""
    c = Canvas()
    def box(x0, y0, x1, y1):
        return (c.X > x0) & (c.X < x1 + 1) & (c.Y > y0) & (c.Y < y1 + 1)
    # the plate round the recess, two pixels, bevelled
    c.set_index(box(1, 1, 62, 46), 116)
    c.set_index(box(1, 1, 62, 1) | box(1, 1, 1, 46), 118)
    c.set_index(box(1, 46, 62, 46) | box(62, 1, 62, 46), 114)
    c.set_index(box(2, 2, 61, 2) | box(2, 2, 2, 45), 117)
    c.set_index(box(2, 45, 61, 45) | box(61, 2, 61, 45), 115)
    # the recess floor, darkest under its top wall
    c.set_index(box(3, 3, 60, 44), 114)
    # walls: shadow along the top and left, a lit lip along the bottom and right
    c.set_index(box(3, 3, 60, 3) | box(3, 3, 3, 44), 112)
    c.set_index(box(4, 4, 59, 4) | box(4, 4, 4, 43), 113)
    c.set_index(box(4, 44, 60, 44) | box(60, 4, 60, 44), 116)
    # sparse wear on the floor: a dark nick with a lit pixel above-left of it
    for x, y in ((13, 11), (14, 11), (47, 15), (21, 36), (22, 37), (52, 33), (36, 24)):
        c.put(x, y, 113)
    for x, y in ((12, 10), (46, 14), (20, 35), (51, 32), (35, 23)):
        c.put(x, y, 116)
    return c


