def jaw_head(c, cx, cy, r, ang, mouth_w, mouth_depth):
    """A spanner head: a disc with an open mouth cut along `ang` (radians, the
    direction the mouth opens)."""
    disc = ellipse(c, cx, cy, r, r)
    ax, ay = math.cos(ang), math.sin(ang)
    nx, ny = -ay, ax
    s = (c.X - cx) * ax + (c.Y - cy) * ay
    t = (c.X - cx) * nx + (c.Y - cy) * ny
    mouth = (s > r - mouth_depth) & (np.abs(t) < mouth_w / 2.0)
    return disc & ~mouth


