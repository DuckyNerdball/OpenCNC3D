def canister(c, base, neck, r, body="red", band=True):
    """A gas bottle lying from base to neck: body, domed shoulder, valve neck and
    cap. Returns (mask, nozzle point, axis unit)."""
    s, t, ln, a, n = axis(c, base, neck)
    body_len = ln - r
    m_body = (s >= 0) & (s <= body_len) & (np.abs(t) <= r)
    sh = cylinder_shade(t, r, n, amb=0.12, kd=0.72, ks=0.35, shin=18)
    c.paint(m_body, body, sh)
    # domed shoulder: a hemisphere on the neck end
    sx, sy = base[0] + a[0] * body_len, base[1] + a[1] * body_len
    du = (c.X - sx) / r
    dv = (c.Y - sy) / r
    along = du * a[0] + dv * a[1]
    m_dome = (du * du + dv * dv <= 1.0) & (along > 0)
    nz = np.sqrt(np.clip(1 - du * du - dv * dv, 0, 1))
    c.paint(m_dome, body, lit(du, dv, nz, amb=0.12, kd=0.72, ks=0.35, shin=18))
    # label band round the body
    if band:
        m_band = m_body & (s >= body_len * 0.40) & (s <= body_len * 0.62)
        c.paint(m_band, "grey", cylinder_shade(t, r, n, amb=0.25))
        m_line = m_body & (np.abs(s - body_len * 0.51) < 0.75)
        c.paint(m_line, "red", cylinder_shade(t, r, n, amb=0.05) * 0.8)
    # base rim: a darker ring at the flat end
    m_rim = m_body & (s < 1.6)
    c.paint(m_rim, body, cylinder_shade(t, r, n) * 0.55)
    # neck and valve
    nr = max(1.6, r * 0.34)
    n0 = ln - r * 0.15
    n1 = ln + r * 0.55
    m_neck = (s >= n0) & (s <= n1) & (np.abs(t) <= nr)
    c.paint(m_neck, "grey", cylinder_shade(t, nr, n, amb=0.2))
    cr = nr + 1.1
    m_cap = (s > n1) & (s <= n1 + r * 0.45) & (np.abs(t) <= cr)
    c.paint(m_cap, "grey", cylinder_shade(t, cr, n, amb=0.25, ks=0.8))
    tip = n1 + r * 0.45
    noz = (base[0] + a[0] * tip, base[1] + a[1] * tip)
    mask = m_body | m_dome | m_neck | m_cap
    return mask, noz, a


def flame_jet(c, start, direction, length, w0, w1, mat="flame", core=1.0):
    """A jet flaring from start along direction: bright core, cooler rim, fading
    toward the tip."""
    p1 = (start[0] + direction[0] * length, start[1] + direction[1] * length)
    s, t, ln, a, n = axis(c, start, p1)
    f = np.clip(s / length, 0, 1)
    half = w0 + (w1 - w0) * np.sqrt(f)
    # taper to a point in the last third
    half = half * np.clip((1.0 - f) / 0.35, 0, 1) ** 0.6
    m = (s >= 0) & (s <= length) & (np.abs(t) <= half)
    across = np.clip(1.0 - np.abs(t) / np.maximum(half, 0.01), 0.0, 1.0)
    heat = across ** 0.7 * (1.0 - 0.8 * f) * core
    c.paint(m, mat, np.clip(heat * 1.25, 0, 1), dither=0.7)
    return m


