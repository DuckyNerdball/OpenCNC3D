BAYER4 = (np.array([[0, 8, 2, 10],
                    [12, 4, 14, 6],
                    [3, 11, 1, 9],
                    [15, 7, 13, 5]], np.float32) + 0.5) / 16.0

# Fixed indices used by name.
BLACK = 12          # opaque (0,0,0); index 0 is the transparent one
WHITE = 15
FRAME_LIGHT = 193   # (188,188,188) top and left edge of a cameo
FRAME_CORNER = 14   # (168,168,168) the two off corners
FRAME_DARK = BLACK  # bottom and right edge

# One light for everything: from the upper left and in front of the screen.
def _unit(v):
    v = np.array(v, np.float64)
    return v / np.linalg.norm(v)

LIGHT = _unit((-0.55, -0.7, 0.75))
HALF = _unit(LIGHT + np.array((0.0, 0.0, 1.0)))


def lit(nx, ny, nz, amb=0.16, kd=0.80, ks=0.45, shin=14.0):
    """Lambert plus a Blinn highlight; normals in screen space (x right, y down,
    z toward the viewer). Returns 0..1."""
    d = np.clip(nx * LIGHT[0] + ny * LIGHT[1] + nz * LIGHT[2], 0.0, 1.0)
    s = np.clip(nx * HALF[0] + ny * HALF[1] + nz * HALF[2], 0.0, 1.0) ** shin
    return np.clip(amb + kd * d + ks * s, 0.0, 1.0)


# ---------------------------------------------------------------------------------
# Canvas: every pixel is a material and a shade until the end, so shadows and glows
# can darken or lighten what is already there, and the palette is applied once.
# ---------------------------------------------------------------------------------

class Canvas(object):
    def __init__(self, w=W, h=H):
        self.w, self.h = w, h
        self.mat = np.full((h, w), "", dtype=object)
        self.shade = np.zeros((h, w), np.float32)
        self.dither = np.zeros((h, w), np.float32)
        self.fixed = np.full((h, w), -1, np.int16)
        yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
        self.X = xx + 0.5
        self.Y = yy + 0.5

    # -- painting -------------------------------------------------------------
    def paint(self, mask, mat, shade, dither=0.0):
        mask = np.asarray(mask, bool)
        self.mat[mask] = mat
        sh = np.broadcast_to(np.asarray(shade, np.float32), mask.shape)
        self.shade[mask] = sh[mask]
        self.dither[mask] = dither
        self.fixed[mask] = -1

    def adjust(self, mask, mul=1.0, add=0.0):
        """Darken or lighten whatever is already painted (shadows, glows)."""
        mask = np.asarray(mask, bool)
        mul = np.broadcast_to(np.asarray(mul, np.float32), mask.shape)
        add = np.broadcast_to(np.asarray(add, np.float32), mask.shape)
        self.shade[mask] = np.clip(self.shade[mask] * mul[mask] + add[mask], 0, 1)

    def put(self, x, y, index):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.fixed[y, x] = index

    def puts(self, pixels, index):
        for x, y in pixels:
            self.put(x, y, index)

    def set_index(self, mask, index):
        self.fixed[np.asarray(mask, bool)] = index

    # -- result ---------------------------------------------------------------
    def indices(self):
        out = np.zeros((self.h, self.w), np.uint8)
        by = np.tile(BAYER4, (self.h // 4 + 1, self.w // 4 + 1))[:self.h, :self.w]
        for name in set(self.mat.ravel()):
            if name == "":
                continue
            ramp = RAMPS[name]
            m = self.mat == name
            q = self.shade[m] * (len(ramp) - 1) + (by[m] - 0.5) * self.dither[m]
            q = np.clip(np.round(q), 0, len(ramp) - 1).astype(np.int32)
            out[m] = np.array(ramp, np.uint8)[q]
        f = self.fixed >= 0
        out[f] = self.fixed[f]
        return out


# ---------------------------------------------------------------------------------
# Shapes. Pixel centres sit at +0.5; every function returns a boolean mask.
# ---------------------------------------------------------------------------------

def ellipse(c, cx, cy, rx, ry):
    return ((c.X - cx) / rx) ** 2 + ((c.Y - cy) / ry) ** 2 <= 1.0


def polygon(c, pts):
    im = Image.new("L", (c.w, c.h), 0)
    ImageDraw.Draw(im).polygon([tuple(p) for p in pts], fill=255)
    return np.array(im) > 0


def axis(c, p0, p1):
    """-> (s, t, length, (ax, ay), (nx, ny)): distance along p0->p1 and signed
    distance across it, for every pixel."""
    dx, dy = p1[0] - p0[0], p1[1] - p0[1]
    ln = math.hypot(dx, dy)
    ax, ay = dx / ln, dy / ln
    nx, ny = -ay, ax
    s = (c.X - p0[0]) * ax + (c.Y - p0[1]) * ay
    t = (c.X - p0[0]) * nx + (c.Y - p0[1]) * ny
    return s, t, ln, (ax, ay), (nx, ny)


def cylinder_shade(t, r, n, flat=1.0, **kw):
    """Shade across a cylinder seen side on: t is the signed distance from the
    axis, r the radius, n the axis normal in the screen. flat < 1 flattens it."""
    u = np.clip(t / r, -1.0, 1.0) * flat
    nz = np.sqrt(np.clip(1.0 - u * u, 0.0, 1.0))
    return lit(n[0] * u, n[1] * u, nz, **kw)


def sphere_shade(c, cx, cy, rx, ry, **kw):
    u = np.clip((c.X - cx) / rx, -1, 1)
    v = np.clip((c.Y - cy) / ry, -1, 1)
    nz = np.sqrt(np.clip(1.0 - u * u - v * v, 0.0, 1.0))
    return lit(u, v, nz, **kw)


def blur(a, n=1):
    a = a.astype(np.float32)
    for _ in range(n):
        p = np.pad(a, 1, mode="edge")
        a = (p[:-2, :-2] + p[:-2, 1:-1] + p[:-2, 2:] +
             p[1:-1, :-2] + p[1:-1, 1:-1] + p[1:-1, 2:] +
             p[2:, :-2] + p[2:, 1:-1] + p[2:, 2:]) / 9.0
    return a


def relief(mask, height=1.0, soft=1, **kw):
    """Shade a flat object with bevelled edges: the normal comes from the slope of
    the softened mask, so the rim catches the light on its upper-left sides."""
    hgt = blur(mask, soft) * height
    gy, gx = np.gradient(hgt)
    nx, ny, nz = -gx * 2.2, -gy * 2.2, np.ones_like(hgt)
    ln = np.sqrt(nx * nx + ny * ny + nz * nz)
    return lit(nx / ln, ny / ln, nz / ln, **kw)


def shift(mask, dx, dy):
    out = np.zeros_like(mask)
    h, w = mask.shape
    ys, yd = (slice(0, h - dy), slice(dy, h)) if dy >= 0 else (slice(-dy, h), slice(0, h + dy))
    xs, xd = (slice(0, w - dx), slice(dx, w)) if dx >= 0 else (slice(-dx, w), slice(0, w + dx))
    out[yd, xd] = mask[ys, xs]
    return out


def grow(mask, n=1):
    m = mask.copy()
    for _ in range(n):
        m = m | shift(m, 1, 0) | shift(m, -1, 0) | shift(m, 0, 1) | shift(m, 0, -1)
    return m


def shrink(mask, n=1):
    return ~grow(~mask, n)


def edge_below_right(mask):
    """Pixels just outside the mask on its lower and right sides."""
    return (shift(mask, 1, 0) | shift(mask, 0, 1)) & ~mask


def edge_above_left(mask):
    return (shift(mask, -1, 0) | shift(mask, 0, -1)) & ~mask


def outline(c, mask, dark=BLACK, light=None):
    """A one-pixel outline: `dark` on the shadow side; on the lit side `light`
    (a palette index) or the same dark."""
    br = edge_below_right(mask)
    al = edge_above_left(mask) & ~br
    c.set_index(br, dark)
    c.set_index(al, dark if light is None else light)


def drop_shadow(c, mask, dx=2, dy=2, mul=0.55):
    c.adjust(shift(mask, dx, dy) & ~mask, mul=mul)


def frame(c):
    """The cameo bevel, exactly as the Win95 cameos carry it."""
    c.fixed[0, :] = FRAME_LIGHT
    c.fixed[:, 0] = FRAME_LIGHT
    c.fixed[-1, :] = FRAME_DARK
    c.fixed[:, -1] = FRAME_DARK
    c.fixed[-1, 0] = FRAME_CORNER
    c.fixed[0, -1] = FRAME_CORNER


def vgrad(c, y0, y1, a, b):
    """Shade running from a at row y0 to b at row y1."""
    return np.clip(a + (b - a) * (c.Y - y0) / float(y1 - y0), min(a, b), max(a, b))


