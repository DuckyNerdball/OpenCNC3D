def sky_with_ground(c, horizon=36, sky="sky", top=0.18, low=0.62, ground="ground",
                    gtop=0.55, gbot=0.25, hills=None):
    """A cameo's backdrop: sky darkening upward, ground darkening toward the
    viewer, and optionally a far line of hills, given as hand-placed (x, height)
    points, hazed into the sky colour as distance does."""
    every = np.ones((c.h, c.w), bool)
    c.paint(every, sky, vgrad(c, 0, horizon, top, low), dither=0.9)
    if hills:
        xs = [p[0] for p in hills]
        hs = [p[1] for p in hills]
        top_y = horizon - np.interp(c.X, xs, hs)
        m = (c.Y >= top_y) & (c.Y < horizon)
        c.paint(m, sky, np.full((c.h, c.w), max(0.0, low - 0.30), np.float32), dither=0.6)
        # the crest catches a little more light than the slopes below it
        ramp = RAMPS[sky]
        crest = ramp[max(0, int((low - 0.18) * (len(ramp) - 1)))]
        c.set_index(m & ~shift(m, 0, 1) & (c.Y < horizon - 1), crest)
    g = c.Y >= horizon
    c.paint(g, ground, vgrad(c, horizon, c.h, gtop, gbot), dither=0.9)
    return g


