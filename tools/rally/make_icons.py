#!/usr/bin/env python3
"""Draws Rally's pixel art and writes game/rally_icons.h from it.

WHAT IT MAKES
  One 64x48 icon per Rally item (RALLY_ITEM_* in game/rally_abi.h, in that order,
  RALLY_ITEM_NONE being the empty item slot), a 15x15 crosshair for the mouse
  pointer while racing and a 16x16 checkered flag. Everything is drawn here, in
  code: hand-placed shapes, analytic shading from one upper-left light and a few
  hand-placed pixels. Nothing is generated by a model, traced from a photo or
  downscaled, and nothing is random, so the output is the same on every run.

STYLE
  The item icons follow the Win95 Tiberian Dawn sidebar cameos, which are 64x48:
  an opaque painted scene filling the whole cell, the subject large and lit from
  the upper left, and a one-pixel bevel round the edge (light grey along the top
  and left, black along the bottom and right, mid grey in the two off corners).
  The icons copy that bevel exactly so they sit in the same frame as the cameos.

PALETTE
  Every pixel is an index into the game's own 256-colour palette, TEMPERAT.PAL,
  read from the 1995 disc's TEMPERAT.MIX (data/dosdata) with menu/tools/mixshp.py
  and widened from the 6-bit DAC the way the engine widens it (v << 2), so an
  icon's colours are exactly the colours the sidebar cameos are drawn in. Index 0
  is transparent, as it is in the game's shapes. Each material is a short ramp of
  palette indices, dark to light; a pixel's shade picks its step in the ramp, and
  a 4x4 ordered dither blends neighbouring steps where a material asks for it.

OUTPUT
  art/interface/rally-v01/<name>.png   each image at 1x, paletted, index 0 transparent
  art/interface/rally-v01/sheet.png    every image at 1x, 2x and 4x beside original
                                       cameos, for review
  game/rally_icons.h                   the same pixels as C arrays for the renderer

Run:  python3 tools/rally/make_icons.py
"""
