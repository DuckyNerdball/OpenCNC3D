def abi_items():
    """The RALLY_ITEM_* names in game/rally_abi.h, in enum order, so a new item in
    the contract stops this script instead of silently going without an icon."""
    text = open(ABI).read()
    m = re.search(r"enum\s*\{([^}]*RALLY_ITEM_NONE[^}]*)\}", text)
    if not m:
        raise SystemExit("could not find the RALLY_ITEM_ enum in %s" % ABI)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    names = [p.split("=")[0].strip() for p in body.split(",")]
    names = [n for n in names if n.startswith("RALLY_ITEM_") and n != "RALLY_ITEM_COUNT"]
    return names


def to_png(idx, pal, path):
    im = Image.fromarray(idx, "P")
    flat = []
    for r, g, b in pal:
        flat += [r, g, b]
    im.putpalette(flat)
    im.info["transparency"] = 0
    im.save(path, transparency=0)


def rgba(idx, pal):
    h, w = idx.shape
    out = np.zeros((h, w, 4), np.uint8)
    for i in np.unique(idx):
        if i == 0:
            continue
        m = idx == i
        out[m, :3] = pal[i]
        out[m, 3] = 255
    return Image.fromarray(out, "RGBA")


def c_array(values, per_line=24, indent="    "):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append(indent + ",".join("%d" % v for v in values[i:i + per_line]) + ",")
    return lines


