def original_cameos(pal, names=("STNK", "ION", "FIX")):
    """Original cameos to compare against: the Win95 64x48 ones from the play
    folder's cameos95.pack if it has been built, and the 1995 DOS disc's own
    32x24 ones (shown doubled to the same 64x48 footprint)."""
    out = []
    if os.path.exists(CAMEOS95):
        d = open(CAMEOS95, "rb").read()
        if d[:8] == b"DOSBAR01":
            _, nshape, _, _ = struct.unpack_from("<IIII", d, 8)
            off = 24 + 768 * 2 + 512
            p8 = d[24 + 768:24 + 1536]
            ppal = [tuple(p8[i * 3:i * 3 + 3]) for i in range(256)]
            found = {}
            for _ in range(nshape):
                nm = d[off:off + 12].rstrip(b"\0").decode()
                off += 12
                fr, w, h = struct.unpack_from("<III", d, off)
                off += 12
                px = np.frombuffer(d[off:off + w * h], np.uint8).reshape(h, w)
                off += fr * w * h
                if nm in names:
                    found[nm] = rgba(px, ppal)
            for nm in names:
                if nm in found:
                    out.append(("%s (Win95)" % nm, found[nm]))
    sys.path.insert(0, os.path.join(ROOT, "menu", "tools"))
    import mixshp  # noqa: E402
    mixes = mixshp.MixSet(DOSDATA, ["CONQUER.MIX"])
    for nm in names:
        rel, raw, _ = mixes.find("%sICON.SHP" % nm)
        if raw is None:
            continue
        shp = mixshp.Shape(raw)
        buf = np.frombuffer(bytes(shp.frame(0)), np.uint8).reshape(shp.height, shp.width)
        im = rgba(buf, pal).resize((shp.width * 2, shp.height * 2), Image.NEAREST)
        # the DOS cameos leave index 0 round the subject; show it on the sidebar grey
        bgim = Image.new("RGBA", im.size, (84, 84, 84, 255))
        bgim.alpha_composite(im)
        out.append(("%s (DOS 2x)" % nm, bgim))
    return out


def make_sheet(pal, icons, cross, flag, path):
    """Every image at 1x, 2x and 4x, with original cameos beside them at the same
    scales, for judging whether the set reads and belongs."""
    from PIL import ImageFont
    font = ImageFont.load_default()
    BG = (28, 30, 34, 255)
    TEXT, DIM = (225, 225, 225), (160, 160, 160)
    pad = 6
    orig = original_cameos(pal)
    imgs = [(n, rgba(icons[n], pal)) for _, n, _ in ITEMS]
    row = orig + imgs

    def scaled(im, k):
        return im.resize((im.width * k, im.height * k), Image.NEAREST)

    grounds = [("grass", (60, 100, 56)), ("sand", (196, 168, 92)),
               ("snow", (220, 220, 228)), ("night", (20, 20, 28))]
    cell_w = 70 + 64 + 128 + 256 + pad * 3
    cell_h = 192 + 16 + pad
    rows = (len(imgs) + 1) // 2
    small_h = 16 * 8 + 18
    width = max(len(row) * (128 + pad) + pad, 2 * cell_w + pad * 2)
    height = (14 + 48 + pad) + (14 + 96 + 12 + pad) + 14 + rows * cell_h + 14 + 2 * small_h + pad
    sheet = Image.new("RGBA", (width, height), BG)
    dr = ImageDraw.Draw(sheet)

    y = 4
    dr.text((pad, y), "1x: original cameos, then the Rally items in RALLY_ITEM_ order",
            fill=TEXT, font=font)
    y += 14
    x = pad
    for _, im in row:
        sheet.alpha_composite(im, (x, y))
        x += 64 + pad
    y += 48 + pad
    dr.text((pad, y), "2x", fill=TEXT, font=font)
    y += 14
    x = pad
    for lbl, im in row:
        sheet.alpha_composite(scaled(im, 2), (x, y))
        dr.text((x, y + 98), lbl, fill=DIM, font=font)
        x += 128 + pad
    y += 96 + 12 + pad
    dr.text((pad, y), "each item at 1x, 2x and 4x", fill=TEXT, font=font)
    y += 14
    for i, (n, im) in enumerate(imgs):
        r, col = divmod(i, 2)
        x0 = pad + col * (cell_w + pad)
        y0 = y + r * cell_h
        dr.text((x0, y0), n, fill=TEXT, font=font)
        xx = x0 + 70
        for k in (1, 2, 4):
            sheet.alpha_composite(scaled(im, k), (xx, y0))
            xx += 64 * k + pad
    y += rows * cell_h
    dr.text((pad, y), "crosshair and flag at 1x, 2x, 4x and 8x on grass, sand, snow and night",
            fill=TEXT, font=font)
    y += 14
    for small in (rgba(cross, pal), rgba(flag, pal)):
        x = pad
        for _, g in grounds:
            for k in (1, 2, 4, 8):
                tile = Image.new("RGBA", (16 * k + 8, 16 * k + 8), g + (255,))
                tile.alpha_composite(scaled(small, k), (4, 4))
                sheet.alpha_composite(tile, (x, y))
                x += 16 * k + 8 + 4
            x += pad * 2
        y += small_h
    sheet.save(path)


