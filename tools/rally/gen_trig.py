#!/usr/bin/env python3
"""Writes brain/vanilla/tiberiandawn/rally_trig.h: a quarter-wave sine table in
16.16 fixed point. Rally's physics runs on every LAN peer and must give the same
bits on every machine, so it never calls the C library's sin/cos; it reads this
table, which is generated once here and committed."""
import math, os, sys

N = 256
vals = [int(round(math.sin(i * math.pi / 2 / N) * 65536)) for i in range(N + 1)]
root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
out = os.path.join(root, "brain", "vanilla", "tiberiandawn", "rally_trig.h")
lines = ["// Generated by tools/rally/gen_trig.py. Do not edit by hand.",
         "// Quarter-wave sine, 257 entries, 16.16 fixed point (65536 = 1.0).",
         "#ifndef TD_RALLY_TRIG_H", "#define TD_RALLY_TRIG_H", "",
         "static const int Rally_Sine_Quarter[257] = {"]
for i in range(0, len(vals), 8):
    lines.append("    " + ", ".join("%d" % v for v in vals[i:i + 8]) + ",")
lines += ["};", "", "#endif", ""]
with open(out, "w") as f:
    f.write("\n".join(lines))
print("wrote", out)
