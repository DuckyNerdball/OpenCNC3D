#!/usr/bin/env python3
"""
OpenCNC3D auto heightmap -- the generator's learned tables, for the map editor.

    python3 export_tables.py            write game/autoheight_tables.h
    python3 export_tables.py --check    exit 1 if that file is not what this would write

The map editor's AUTO HEIGHTMAP runs the same generator as tools/autoheight/generate.py,
ported to C++ in game/autoheight_mod.h. Everything the generator LEARNS from the 55
cartridge maps (each icon's corner offsets from its terrace and their spread, each
cliff icon's corner fractions, the rung each step template delivers) and every number it
is TUNED by is written into one header here, so the two can never disagree about a
number: the C++ carries the arithmetic and nothing else.
"""
import os, sys
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import corpus as C
import generate as G

OUT = os.path.join(C.ROOT, "game", "autoheight_tables.h")
TUNE = ("RUNG", "W_SMOOTH", "W_DIAG", "W_PLACE", "W_BASE", "W_BASE_WATER", "W_WATERLAND",
        "W_BEACHLAND", "W_FOOT", "IRLS_ITERS", "IRLS_EPS",
        "STEP_MIN_SHARE", "WATER_BANK_SHARE", "BASE_SITE_R", "RAMP_LIMIT", "RAMP_ROUNDS",
        "RAMP_RING", "RAMP_ITERS", "SWELL_MAX", "SWELL_NEAR", "SWELL_FULL", "SWELL_SIGMA",
        "SWELL_LOW", "SWELL_HIGH", "SWELL_BIAS", "SWELL_STEP", "SWELL_PASSES")


def f(v):
    s = "%.6g" % float(v)
    return s + ("f" if ("." in s or "e" in s) else ".0f")


def build():
    model = G.train(C.training())
    nt = len(C.TT)
    # template slot nt is the "no template" cell (255): one icon
    base, icons = [], []
    for t in list(range(nt)) + [255]:
        base.append(len(icons))
        if t == 255:
            n, w, h = 1, 1, 1
        else:
            _, _, _, _, w, h = C.TT[t]
            n = w * h
        for i in range(n):
            mu, sp = G.offset_prior(model, t, i)
            fr = G.frac_prior(model, t, i, w, h) if t in G.STEP_DIR else np.zeros(4)
            icons.append((mu, sp, fr))
    base.append(len(icons))
    L = []
    L.append("/* GENERATED by tools/autoheight/export_tables.py from the 55 cartridge maps that ship")
    L.append("   a hand-made heightmap. Do not edit: change the generator and run it again;")
    L.append("   `export_tables.py --check` says whether this file is current. */")
    L.append("#pragma once")
    L.append("")
    L.append("/* the generator's tuning, exactly as tools/autoheight/generate.py has it */")
    for k in TUNE:
        L.append(f"#define AHT_{k} {float(getattr(G, k))!r}")
    L.append(f"#define AHT_N_TEMPLATES {nt}")
    L.append(f"#define AHT_N_ICONS {len(icons)}")
    L.append("")
    L.append("/* the five rungs, and the template families (CLEAR WATER SHORE SLOPE BRUSH PATCH")
    L.append("   BOULDER ROAD RIVER FORD FALLS BRIDGE, in that order) */")
    L.append("static const float AHT_LADDER[5] = { " + ", ".join(f(v) for v in C.LADDER) + " };")
    for nm in C.FAMILIES:
        L.append(f"#define AHT_FAM_{nm} {C.FAM[nm]}")
    fam = [int(C.FAMILY_OF[t]) for t in range(256)]
    L.append("static const signed char AHT_FAMILY[256] = {" + ",".join(map(str, fam)) + "};")
    dx = [G.STEP_DIR.get(t, (0, 0))[0] for t in range(256)]
    dy = [G.STEP_DIR.get(t, (0, 0))[1] for t in range(256)]
    L.append("/* the high side of every template that carries a whole rung (cliffs, waterfalls);")
    L.append("   0,0 for every other template */")
    L.append("static const signed char AHT_STEP_DX[256] = {" + ",".join(map(str, dx)) + "};")
    L.append("static const signed char AHT_STEP_DY[256] = {" + ",".join(map(str, dy)) + "};")
    st = []
    for t in range(256):
        v = model["step"].get(t, G.RUNG)
        st.append(G.RUNG if v < 32 else v)
    L.append("/* the rise a placement of that template delivers between its two sides, bytes */")
    L.append("static const float AHT_STEP[256] = {" + ",".join(f(v) for v in st) + "};")
    L.append("/* where each template's icons start in the per-icon tables (slot AHT_N_TEMPLATES")
    L.append("   is the cell no template claims) */")
    L.append(f"static const unsigned short AHT_ICON_BASE[{len(base)}] = {{" + ",".join(map(str, base)) + "};")
    L.append("/* per icon: corner offsets from its terrace (nw ne sw se), their spread, and for a")
    L.append("   step template the corners' fraction of the way from its low side to its high */")
    L.append("static const float AHT_OFF_MU[AHT_N_ICONS][4] = {")
    L += ["  {" + ",".join(f(v) for v in mu) + "}," for mu, sp, fr in icons]
    L.append("};")
    L.append("static const float AHT_OFF_SP[AHT_N_ICONS][4] = {")
    L += ["  {" + ",".join(f(v) for v in sp) + "}," for mu, sp, fr in icons]
    L.append("};")
    L.append("static const float AHT_FRAC[AHT_N_ICONS][4] = {")
    L += ["  {" + ",".join(f(v) for v in fr) + "}," for mu, sp, fr in icons]
    L.append("};")
    return "\n".join(L) + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        print("game/autoheight_tables.h is " + ("current" if cur == text else "STALE: run export_tables.py"))
        sys.exit(0 if cur == text else 1)
    open(OUT, "w").write(text)
    print("wrote", OUT, f"({text.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
