#!/usr/bin/env python3
"""
OpenCNC3D auto heightmap -- pictures of generated against real.

    python3 compare.py SCB22EB SCG07EA [--gen generate] [--out out]

Writes out/cmp_<gen>_<SCEN>.png: the tile art, the cartridge's own relief (for a
map that has one) and the generated relief, side by side. A map that ships a
heightmap is generated by a model trained WITHOUT its own mission, exactly as the
scoreboard does it, so the picture shows what the score measures.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import corpus as C, generate as G, render as R, score as S

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    args = sys.argv[1:]
    gname, out = "generate", os.path.join(HERE, "out")
    if "--gen" in args:
        k = args.index("--gen"); gname = args[k + 1]; del args[k:k + 2]
    if "--out" in args:
        k = args.index("--out"); out = args[k + 1]; del args[k:k + 2]
    os.makedirs(out, exist_ok=True)
    maps = C.training()
    byid = {m.id: m for m in maps}
    for s in args:
        m = byid.get(s) or C.Map(s)
        model = G.train([x for x in maps if S.mission(x.id) != S.mission(s)])
        g = getattr(G, gname)(m, model)
        p = os.path.join(out, f"cmp_{gname}_{s}.png")
        R.compare_image(m, [g], px=8).save(p)
        print(p)


if __name__ == "__main__":
    main()
