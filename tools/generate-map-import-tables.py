#!/usr/bin/env python3
"""Freeze the existing RA height adapter/native tile averages for the native importer.

Usage: python3 tools/generate-map-import-tables.py /path/to/asset-complete/source
No Python or source artwork is needed by the installed importer.
"""
import hashlib
import pathlib
import struct
import sys

HERE = pathlib.Path(__file__).resolve().parents[1]
SOURCE = pathlib.Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else HERE
sys.path[:0] = [str(SOURCE / "tools/ra3d"), str(SOURCE / "tools/autoheight")]
import ra_heights as H
import numpy as np

B = H.B
td = {t[0]: i for i, t in enumerate(H.TD.TT)}
lines = ["// Generated by tools/generate-map-import-tables.py; do not edit.",
         "// Adapter is tools/ra3d/ra_heights.py: picture, close namesake, native land.",
         "#pragma once",
         "struct MapImportRaTile { unsigned short t; unsigned char i, ht, hi, land, r, g, b; };",
         "// land: 0 ground, 1 water, 2 rock, 3 road, 4 beach, 5 rough"]
inputs = ["tools/ra3d/ra_heights.py", "tools/ra3d/ra_map.py", "tools/ra3d/bake_ra_terrain3d.py",
          "brain/vanilla/redalert/defines.h", "brain/vanilla/redalert/cdata.cpp",
          "brain/vanilla/redalert/bdata.cpp", "game/terrain_tiles.h",
          "data/radata/SNOW.MIX", "data/radata/TEMPERAT.MIX", "data/radata/INTERIOR.MIX",
          "data/radata/LOCAL.MIX",
          "tools/bakery/sharecopy/assets/terrain/SNOW_tiles.png",
          "tools/bakery/sharecopy/assets/terrain/TEMPERAT_tiles_dos.png"]
expansion = SOURCE / "data/radata/expansions/aftermath/EXPAND2.MIX"
if expansion.is_file():
    inputs.append(str(expansion.relative_to(SOURCE)))
for rel in inputs:
    lines.append("// SHA256 " + hashlib.sha256((SOURCE / rel).read_bytes()).hexdigest() + " " + rel)
for bank in ("RATEMP", "RASNOW", "RAINT"):
    land = H.ra_land_codes(bank)
    pic = B.picture_match(bank)
    same = H.close_namesakes(bank, td) if bank != "RAINT" else {}
    pal = B.palette(B.THEATERS[bank][2])
    mixname, extension = B.THEATERS[bank][:2]
    base_mix = H.RaMix(str(SOURCE / "data/radata" / mixname))
    extra_mix = H.RaMix(str(expansion)) if expansion.is_file() else None
    slots = {(t, i): px for t, i, px in B.bank_slots(bank)}
    clear = slots[(0, 0)]
    # Native Land_Type reads control icons even when their art is masked. Original
    # Soviet 6 contains BRIDGE2 masked icons outside the playable rectangle.
    # Ant HILL01 lives in EXPAND2.MIX rather than the base theater MIX.
    for t, name in B.bank_templates(bank):
        raw = base_mix.read(name + "." + extension)
        if raw is None and extra_mix:
            raw = extra_mix.read(name + "." + extension)
        if raw is None:
            continue
        fields = struct.unpack_from("<6h7i", raw)
        count, mw, mh, control = fields[2], fields[4], fields[5], fields[11]
        pixels = B._ct.icons(raw, name)
        for i in range(count):
            slots.setdefault((t, i), pixels.get(i, clear))
            land[(t, i)] = H.RA_LAND[raw[control + i % max(1, mw * mh)] & 15]
    lines.append("static const MapImportRaTile MAP_IMPORT_" + bank + "[] = {")
    for (t, i), px in sorted(slots.items()):
        l = land.get((t, i), "CLEAR")
        if t == 0:
            ht, hi = 255, 0
        elif (t, i) in pic:
            ht, hi = pic[(t, i)]
            if ht == 0:
                ht, hi = 255, 0
        elif t in same and i < H.TD.TT[same[t]][4] * H.TD.TT[same[t]][5]:
            ht, hi = same[t], i
        else:
            ht, hi = (td["W1"], 0) if l in ("WATER", "RIVER") else (td["SH3"], 0) if l == "ROCK" else (255, 0)
        rgb = pal[np.frombuffer(px, np.uint8)].mean(axis=0).round().astype(int)
        lc = {"WATER": 1, "RIVER": 1, "ROCK": 2, "ROAD": 3, "BEACH": 4, "ROUGH": 5}.get(l, 0)
        lines.append("{%d,%d,%d,%d,%d,%d,%d,%d}," % (t, i, ht, hi, lc, *rgb))
    lines.append("};")
    print(bank, len(slots), flush=True)
lines += ["struct MapImportRaFoot { const char* name; unsigned char n; signed char dx[16], dy[16]; };",
          "static const MapImportRaFoot MAP_IMPORT_RA_FOOT[] = {"]
for name, offsets in sorted(H.footprints().items()):
    if len(offsets) > 16:
        raise ValueError(name)
    lines.append('{"%s",%d,{%s},{%s}},' % (name, len(offsets), ",".join(str(x) for x, y in offsets), ",".join(str(y) for x, y in offsets)))
lines.append("};")
(HERE / "app/map_import_ra_tables.h").write_text("\n".join(lines) + "\n")
