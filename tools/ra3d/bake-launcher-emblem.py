#!/usr/bin/env python3
"""Bake the approved Red Alert cover circle into the launcher's DOS palette."""

from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "art/ra3d/launcher-green-circle.png"
PACK = ROOT / "playable/dosmenu.pack"
OUTPUT = ROOT / "launcher/ra_emblem.h"
SIZE = 48

blob = PACK.read_bytes()
assert blob[:8] == b"DOSBAR01"
pal = blob[8 + 16 + 768:8 + 16 + 768 * 2]
assert len(pal) == 768
colors = [tuple(pal[i * 3:i * 3 + 3]) for i in range(256)]
image = Image.open(SOURCE).convert("RGBA").resize((SIZE, SIZE), Image.Resampling.LANCZOS)

pixels = []
for red, green, blue, alpha in image.getdata():
    if alpha < 128:
        pixels.append(0)  # transparent sentinel; palette index 0 is excluded below
        continue
    pixels.append(min(range(1, 256), key=lambda i:
                      (red - colors[i][0]) ** 2 +
                      (green - colors[i][1]) ** 2 +
                      (blue - colors[i][2]) ** 2))

rows = []
for y in range(SIZE):
    row = pixels[y * SIZE:(y + 1) * SIZE]
    rows.append("    " + ", ".join(f"{pixel:3d}" for pixel in row) + ",")
OUTPUT.write_text("/* Generated by tools/ra3d/bake-launcher-emblem.py.\n"
                  " * Index 0 is transparent; all other values use dosmenu.pack. */\n"
                  "static const unsigned char ra_emblem_pixels[48 * 48] = {\n" +
                  "\n".join(rows) + "\n};\n")
print(f"baked {SOURCE} to {OUTPUT}")
