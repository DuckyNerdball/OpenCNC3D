#!/usr/bin/env python3
"""Preserve the RA type-to-retail-text-ID join for translated sidebar names.
The English HUD titles stay authored; localized IDs come from the engine's own
constructors and conquer.h, never TD's unrelated string numbers.

Each row also carries the English text conquer.h gives that string number in its
comment. That is the fallback for a type the authored HUD titles do not list (the
Aftermath units, civilians, fakes): the 1996 English string table on the disc stops
before the expansions' numbers, so without it such a unit's card printed its type code.
"""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[2]
engine=root/'brain/vanilla/redalert'
defs={m[1]:int(m[2]) for m in re.finditer(r'^#define\s+(TXT_\w+)\s+(\d+)\b',(engine/'conquer.h').read_text(),re.M)}
english={int(m[1]):m[2].strip() for m in re.finditer(r'^#define\s+TXT_\w+\s+(\d+)\b[ \t]*//[ \t]*(.*)$',(engine/'conquer.h').read_text(),re.M)}
names={}
for file in ['bdata.cpp','idata.cpp','udata.cpp','aadata.cpp','vdata.cpp']:
 text=(engine/file).read_text(encoding='latin1')
 for m in re.finditer(r'\b(TXT_\w+)\b\s*,(?:[^"\n]*\n)*?[^"\n]*"([A-Z0-9]{2,8})"',text):
  if m[1]in defs:names.setdefault(m[2],defs[m[1]])
assert names['POWR']==defs['TXT_POWER'] and names['FACT']==defs['TXT_CONST_YARD']
lines=['/* Generated by tools/ra3d/bake-language-names.py from the RA engine. */','struct RA_LanguageName { const char* asset; int text; const char* english; };','static const RA_LanguageName RA_LANGUAGE_NAMES[] = {']
import json
lines += ['    {"%s", %d, %s},'%(k,v,json.dumps(english.get(v,'')) if v else '""')for k,v in sorted(names.items())]
lines += ['};','']
(root/'game/ra_language_names.h').write_text('\n'.join(lines));print('RA name IDs:',len(names))
