"""Generate the Red Alert score table from the original engine source."""

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
source = ROOT / "brain/vanilla/redalert"
theme_text = (source / "theme.cpp").read_text(encoding="latin-1")
conquer_text = (source / "conquer.h").read_text(encoding="latin-1")

titles = {}
for name, title in re.findall(r"#define\s+(TXT_THEME_\w+)\s+\d+\s*//\s*(.+)", conquer_text):
    titles[name] = title.strip()

block = theme_text.split("ThemeClass::_themes[THEME_COUNT] = {", 1)[1].split("\n};", 1)[0]
rows = []
pattern = re.compile(
    r'\{"([A-Z0-9_]+)",\s*(TXT_THEME_\w+),\s*(\d+),\s*(\d+),'
    r'\s*(true|false),\s*(true|false),\s*(true|false),\s*([^}]+)\}')
for match in pattern.finditer(block):
    name, title_key, scenario, duration, normal, variation, repeat, owner = match.groups()
    if title_key not in titles:
        raise ValueError(f"missing original title for {name}: {title_key}")
    sides = (1 if "HOUSEF_ALLIES" in owner else 0) | (2 if "HOUSEF_SOVIET" in owner else 0)
    title = titles[title_key].replace('"', '\\"')
    rows.append((name, int(scenario), int(duration), normal == "true",
                 variation == "true", repeat == "true", title, sides))
if len(rows) != 39:
    raise ValueError(f"expected 39 original Red Alert themes, got {len(rows)}")

out = ["/* Generated by audio/tools/gen_ra_theme_table.py from Red Alert theme.cpp",
       " * and conquer.h. Regenerate from the original source, do not hand edit. */",
       "#ifndef RA_THEME_TABLE_H", "#define RA_THEME_TABLE_H", "",
       "#define RA_THEME_COUNT 39", "typedef struct { ThemeEntry theme; unsigned sides; } RAThemeEntry;",
       "static const RAThemeEntry ra_theme[RA_THEME_COUNT] = {"]
for name, scenario, duration, normal, variation, repeat, title, sides in rows:
    out.append(f'    {{{{"{name}", {scenario}, {duration}, {int(normal)}, '
               f'{int(variation)}, {int(repeat)}, "{title}"}}, {sides}}},')
out.extend(["};", "", "#endif /* RA_THEME_TABLE_H */", ""])
(ROOT / "audio/ra_theme_table.h").write_text("\n".join(out))
print(f"wrote {len(rows)} original Red Alert themes")
